import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { compileFile, version as cashcVersion, utils } from 'cashc';
import type { Artifact } from '@cashscript/utils';

const REQUIRED_CASHC_VERSION = '0.14.0';
const CONTRACTS = ['AtPriceBuy', 'AtPriceSell'] as const;

const packageRoot = new URL('../', import.meta.url);
const pathIn = (relative: string): string => fileURLToPath(new URL(relative, packageRoot));

if (cashcVersion !== REQUIRED_CASHC_VERSION) {
  throw new Error(`cashc ${REQUIRED_CASHC_VERSION} is required, found ${cashcVersion}`);
}

const withoutTimestamp = ({ updatedAt: _updatedAt, ...rest }: Artifact): Omit<Artifact, 'updatedAt'> => rest;

// Recompiling unchanged sources must not churn the committed artifacts, so the previous
// timestamp is kept whenever everything else is identical.
const stabilise = (fresh: Artifact, jsonPath: string): Artifact => {
  if (!existsSync(jsonPath)) return fresh;
  const previous = JSON.parse(readFileSync(jsonPath, 'utf8')) as Artifact;
  const unchanged = JSON.stringify(withoutTimestamp(previous)) === JSON.stringify(withoutTimestamp(fresh));
  return unchanged ? { ...fresh, updatedAt: previous.updatedAt } : fresh;
};

const tsModules: string[] = [];
for (const name of CONTRACTS) {
  const warnings: string[] = [];
  const compiled = compileFile(pathIn(`src/${name}.cash`), {
    warningListener: (warning) => warnings.push(warning.message),
  });
  if (warnings.length > 0) {
    throw new Error(`${name}.cash compiled with warnings:\n${warnings.join('\n')}`);
  }
  const jsonPath = pathIn(`artifacts/${name}.json`);
  const artifact = stabilise(compiled, jsonPath);
  writeFileSync(jsonPath, utils.formatArtifact(artifact, 'json'));
  tsModules.push(
    utils.formatArtifact(artifact, 'ts').replace(/^export default /, `export const ${name}Artifact = `),
  );
  console.log(
    `${name}: ${artifact.bytecode.split(' ').length} ops, fingerprint ${artifact.fingerprint ?? 'none'}`,
  );
}

const header = `// Generated by scripts/compile.ts from src/*.cash with cashc ${REQUIRED_CASHC_VERSION}. Do not edit.\n`;
writeFileSync(pathIn('src/artifacts.ts'), `${header}\n${tsModules.join('\n')}`);
